function translate(source, locale) {
  return locale !== 'zh' && translations[source] && translations[source][locale]
    ? translations[source][locale]
    : source;
}

function translateSeedText(source, locale) {
  const exact = translate(source, locale);
  if (exact !== source || typeof source !== 'string') return exact;
  return source.replace(/农业无人飞机|收割机|旋耕机|播种机|拖拉机|马力|载重|幅宽|行播种/g, (term) =>
    translate(term, locale),
  );
}

function labels(locale) {
  const result = {};
  Object.keys(sources).forEach((key) => {
    result[key] = translate(sources[key], locale);
  });
  Object.keys(extra).forEach((key) => {
    result[key] = extra[key][locale === 'ug' ? 1 : locale === 'kk' ? 2 : 0];
  });
  return result;
}

